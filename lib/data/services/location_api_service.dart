    required double lat,
    required double lng,
    int width = 1200,
    int height = 800,
    int fov = 100,
    int heading = 0,
    int pitch = 0,
  }) {
    final key = DefaultFirebaseOptions.web.apiKey;
    return '$_streetViewBase?size=${width}x$height&location=$lat,$lng&fov=$fov&heading=$heading&pitch=$pitch&key=$key';
