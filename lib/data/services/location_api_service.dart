  /// Returns deterministically or purely randomly chosen unique locations for a match
  List<LocationItem> generateMatchLocations({int count = 10, int? seed}) {
    final list = List<LocationItem>.from(_curatedLocations);
    // Non-deterministic random if seed is not explicitly specified
    final rng = seed != null
        ? math.Random(seed)
        : math.Random(DateTime.now().microsecondsSinceEpoch);
    list.shuffle(rng);
    return list.take(count).toList();
  }
